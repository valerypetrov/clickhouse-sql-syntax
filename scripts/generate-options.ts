function rows<R>(query: string): R[] {
  const output = execFileSync(clickhouse, ["local", "--query", `${query} FORMAT JSONEachRow`], { encoding: "utf8", maxBuffer: 1 << 28 });
  return output.trim().split("\n").filter(Boolean).map((line) => JSON.parse(line) as R);
}

const version = execFileSync(clickhouse, ["local", "--query", "SELECT version()"], { encoding: "utf8" }).trim();

function plain(markdown: string): string {
  return markdown.replace(/\[([^\]]*)\]\([^)]*\)/g, "$1").replace(/\s+/g, " ").trim();
}

function shorten(text: string, limit: number): string {
  if (text.length <= limit) return text;
  const cut = text.lastIndexOf(". ", limit);
  return cut > limit / 3 ? text.slice(0, cut + 1) : `${text.slice(0, limit).trimEnd()}…`;
}

/** The first prose paragraph of a text, as plain text. */
function summary(markdown: string, limit: number): string {
  const paragraphs = markdown
    .replace(/```[\s\S]*?```/g, "")
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p && !/^(import |#|\||<|:::)/.test(p));
  const first = paragraphs[0]?.endsWith(":") ? paragraphs.slice(0, 2).join(" ") : (paragraphs[0] ?? "");
  return shorten(plain(first), limit);
}

function compact(value: object): string {
  const kept = Object.entries(value).filter(([, v]) => v !== undefined && v !== "" && v !== false && !(Array.isArray(v) && v.length === 0));
  return JSON.stringify(Object.fromEntries(kept));
}

function write(file: string, source: string, lines: string[]): void {
  const header = [`// Generated by scripts/generate-options.ts from ${source}; do not edit.`, `// ClickHouse ${version}. Empty strings, empty lists and false are left out.`];
  writeFileSync(join(outDir, file), [...header, ...lines, ""].join("\n"));
}

const quote = (text: string) => `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

/** The values of an enum from ClickHouse's "Must be one of [...]" message. */
function enumValues(message: string | undefined): string[] | undefined {
  const match = /Must be one of \[([^\]]*)\]/.exec(message ?? "");
  return match ? [...match[1]!.matchAll(/'([^']*)'/g)].map((m) => m[1]!) : undefined;
}

/** Whether the outcome says the name is not a setting there. */
const isUnknown = (outcome: Outcome) =>
  !outcome.ok && (outcome.code === 115 || /^Unknown setting\b/.test(outcome.message ?? "")) && !/while setting/.test(outcome.message ?? "");

/** A value of the type that ClickHouse takes for a probe of the name, or that it rejects with a message of the setting itself. */
function probeValue(setting: { type: string; default?: string }): string {
  if (setting.default !== undefined && /^-?\d+(\.\d+)?$/.test(setting.default)) return setting.default;
  if (setting.type === "Bool") return "0";
  if (/^(U?Int|Float|Double|Seconds|Milliseconds|NonZero|MaxThreads)/.test(setting.type)) return "1";
  return quote(setting.default ?? "");
}

const PROBE_ENUM = "zz_probe_value";

/** Enum values of each setting whose type is not a plain one, by a statement that sets it to a value no enum has. */
function probeEnums<S extends { name: string; type: string }>(settings: readonly S[], statement: (name: string, value: string) => string, setup?: string[]) {
  const plainType = /^(Bool|U?Int\d*|Float|Double|String|Char|Map|Seconds|Milliseconds|NonZeroUInt64|MaxThreads|Timezone|URI|UInt64Auto|FloatAuto|DoubleAuto|BoolAuto|BoolForce)$/;
  const candidates = settings.filter((s) => !plainType.test(s.type));
  const outcomes = probe(clickhouse, candidates.map((s) => statement(s.name, quote(PROBE_ENUM))), { setup });
  const found = new Map<string, { values: string[]; multi: boolean }>();
  candidates.forEach((s, i) => {
    const values = enumValues(outcomes[i]!.message);
    if (values?.length) found.set(s.name, { values, multi: false });
  });
  // A multi-valued enum takes a comma-separated list of its values.
  const multi = [...found].filter(([, e]) => e.values.length >= 2);
  const lists = probe(clickhouse, multi.map(([name, e]) => statement(name, quote(`${e.values[0]},${e.values[1]}`))), { setup });
  multi.forEach(([, e], i) => (e.multi = lists[i]!.ok || !enumValues(lists[i]!.message)));
  return found;
}

