// Regenerates the completion catalog of functions, settings, engines, formats, combinators and time zones from ClickHouse.
// Usage: npx tsx scripts/generate-catalog.ts --clickhouse <clickhouse binary>

import { execFileSync, spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

import { argumentTypes, argumentValues } from "./function-docs.js";

const { values: args } = parseArgs({ options: { clickhouse: { type: "string" } } });

if (!args.clickhouse) {
  console.error("Usage: npx tsx scripts/generate-catalog.ts --clickhouse <clickhouse binary>");
  process.exit(2);
}

const outDir = join(import.meta.dirname, "..", "packages", "core", "src", "generated");

function rows<R>(query: string): R[] {
  const output = execFileSync(args.clickhouse!, ["local", "--query", `${query} FORMAT JSONEachRow`], {
    encoding: "utf8",
    maxBuffer: 1 << 28,
  });
  return output
    .trim()
    .split("\n")
    .map((line) => JSON.parse(line) as R);
}

const version = execFileSync(args.clickhouse, ["local", "--query", "SELECT version()"], { encoding: "utf8" }).trim();

/** Markdown as plain text: links keep their text, whitespace becomes single spaces. */
function plain(markdown: string): string {
  return markdown
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/** Cuts a text at the last sentence end before `limit`, or at `limit` with an ellipsis. */
function shorten(text: string, limit: number): string {
  if (text.length <= limit) return text;
  const cut = text.lastIndexOf(". ", limit);
  return cut > limit / 3 ? text.slice(0, cut + 1) : `${text.slice(0, limit).trimEnd()}…`;
}

/** The first prose paragraph of a documentation text, skipping imports, headings, tables, code and notes. */
function summary(markdown: string, limit: number): string {
  const text = markdown
    .replace(/```[\s\S]*?```/g, "")
    .replace(/<([A-Z]\w*)\b[^>]*>[\s\S]*?<\/\1>/g, "")
    .replace(/<[A-Z]\w*\b[^>]*\/>/g, "")
    .replace(/^:::[\s\S]*?^:::$/gm, "");
  const paragraphs = text
    .split(/\n\s*\n/)
    .map((p) => p.trim())
    .filter((p) => p && !/^(import |#|\||<|Cloud default value)/.test(p));
  // A paragraph that ends with ":" introduces the next one, usually a list.
  const first = paragraphs[0]?.endsWith(":") ? paragraphs.slice(0, 2).join(" ") : (paragraphs[0] ?? "");
  return shorten(plain(first), limit);
}

interface Argument {
  name: string;
  description: string;
  types?: string[];
  values?: string[][];
}

/** The items "- `name` — description" of a documented argument list, with the types and values each one names. */
function argumentList(markdown: string, functionDescription: string): Argument[] {
  return markdown.split(/(?:^|\s)- (?=`)/).flatMap((item) => {
    const match = /^`([^`]+)`\s*[—–-]?\s*([\s\S]*)$/.exec(item.trim());
    if (!match) return [];
    const [, name, text] = match as unknown as [string, string, string];
    const types = argumentTypes(text);
    const values = argumentValues(text, functionDescription, name);
    return [{ name, description: shorten(plain(text), 120), ...(types.length ? { types } : {}), ...(values.length ? { values } : {}) }];
  });
}

/** An object without its empty strings, empty arrays and false values, to keep the files small. */
function compact(value: Record<string, unknown>): string {
  const kept = Object.entries(value).filter(([, v]) => v !== "" && v !== false && !(Array.isArray(v) && v.length === 0));
  return JSON.stringify(Object.fromEntries(kept));
}

function write(file: string, source: string, declaration: string[], name: string, type: string, items: object[]): void {
  writeFileSync(
    join(outDir, file),
    [
      `// Generated by scripts/generate-catalog.ts from ${source}; do not edit.`,
      `// ClickHouse ${version}. Empty strings, empty lists and false are left out.`,
      ...declaration,
      "",
      `export const ${name}: readonly ${type}[] = [`,
      ...items.map((item) => `  ${compact(item as Record<string, unknown>)},`),
      "];",
      "",
    ].join("\n"),
  );
}

const ARGUMENT = [
  "export interface Argument {",
  "  name: string;",
  "  description: string;",
  "  /** The types its documentation ends with, such as `String` or `(U)Int*`. */",
  "  types?: readonly string[];",
  "  /** The values its documentation lists, each with the other spellings that ClickHouse takes for it. */",
  "  values?: readonly (readonly string[])[];",
  "}",
  "",
];

interface FunctionRow {
  name: string;
  is_aggregate: number;
  case_insensitive: number;
  alias_to: string;
  syntax: string;
  arguments: string;
  parameters: string;
  returned_value: string;
  description: string;
  categories: string;
}

// Names that start with "_" are internal helpers that queries do not call.
const functions = rows<FunctionRow>(
  "SELECT name, is_aggregate, case_insensitive, alias_to, syntax, arguments, parameters, returned_value, description, " +
    "categories FROM system.functions WHERE NOT startsWith(name, '_') AND categories != 'Internal' ORDER BY name",
).map((r) => ({
  name: r.name,
  aggregate: r.is_aggregate === 1,
  caseInsensitive: r.case_insensitive === 1,
  aliasTo: r.alias_to,
  syntax: r.syntax.trim(),
  arguments: argumentList(r.arguments, r.description),
  parameters: argumentList(r.parameters, r.description),
  returns: shorten(plain(r.returned_value), 120),
  description: summary(r.description, 250),
  category: r.categories.trim(),
}));

write(
  "functions.ts",
  "system.functions",
  [
    ...ARGUMENT,
    "export interface FunctionInfo {",
    "  name: string;",
    "  /** An aggregate function, which takes combinators such as sumIf. */",
    "  aggregate?: boolean;",
    "  /** Whether the name may be written in any letter case, like `COUNT` for `count`. */",
    "  caseInsensitive?: boolean;",
    "  /** The function this name is an alias of. */",
    "  aliasTo?: string;",
    "  /** How it is called, such as `toDate(x)`; one form per line. */",
    "  syntax?: string;",
    "  arguments?: readonly Argument[];",
    "  /** The parameters of a parametric aggregate function, as `level` in quantile(level)(x). */",
    "  parameters?: readonly Argument[];",
    "  returns?: string;",
    "  /** The first paragraph of the documentation, as plain text. */",
    "  description?: string;",
    "  category?: string;",
    "}",
  ],
  "FUNCTIONS",
  "FunctionInfo",
  functions,
);

interface SettingRow {
  name: string;
  type: string;
  default: string;
  description: string;
  alias_for: string;
}

const settings = rows<SettingRow>(
  "SELECT name, type, default, description, alias_for FROM system.settings WHERE NOT is_obsolete ORDER BY name",
).map((r) => ({ name: r.name, type: r.type, default: r.default, aliasTo: r.alias_for, description: summary(r.description, 200) }));

write(
  "settings.ts",
  "system.settings (obsolete settings left out)",
  [
    "export interface SettingInfo {",
    "  name: string;",
    "  /** The type of its value, such as UInt64 or Bool. */",
    "  type: string;",
    "  default?: string;",
    "  /** The setting this name is an alias of. */",
    "  aliasTo?: string;",
    "  description?: string;",
    "}",
  ],
  "SETTINGS",
  "SettingInfo",
  settings,
);

interface EngineRow {
  name: string;
  syntax: string;
  description: string;
}

const engines = rows<EngineRow>("SELECT name, syntax, description FROM system.table_engines ORDER BY name").map((r) => ({
  name: r.name,
  syntax: r.syntax.trim(),
  description: summary(r.description, 300),
}));

write(
  "table-engines.ts",
  "system.table_engines",
  [
    "export interface TableEngineInfo {",
    "  name: string;",
    "  /** How a table uses it, such as `ENGINE = Memory`. */",
    "  syntax?: string;",
    "  description?: string;",
    "}",
  ],
  "TABLE_ENGINES",
  "TableEngineInfo",
  engines,
);

interface FormatRow {
  name: string;
  is_input: number;
  is_output: number;
  description: string;
}

const formatRows = rows<FormatRow>("SELECT name, is_input, is_output, description FROM system.formats ORDER BY name");

// system.formats does not say which formats write each row by itself, as formatRow() needs, so formatRow() is asked.
const rowFormats = new Set(
  spawnSync(
    args.clickhouse,
    [
      "local",
      "--ignore-error",
      "--query",
      formatRows
        .filter((r) => r.is_output === 1 && /^\w+$/.test(r.name))
        .map((r) => `SELECT '${r.name}' FROM (SELECT formatRow('${r.name}', 1 AS x));`)
        .join("\n"),
    ],
    { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
  ).stdout.split("\n"),
);

const formats = formatRows.map((r) => ({
  name: r.name,
  input: r.is_input === 1,
  output: r.is_output === 1,
  rows: rowFormats.has(r.name),
  description: summary(r.description, 300),
}));

write(
  "formats.ts",
  "system.formats",
  [
    "export interface FormatInfo {",
    "  name: string;",
    "  /** Whether INSERT can read data in it. */",
    "  input?: boolean;",
    "  /** Whether SELECT can write its result in it. */",
    "  output?: boolean;",
    "  /** Whether formatRow() can write one row in it. */",
    "  rows?: boolean;",
    "  description?: string;",
    "}",
  ],
  "FORMATS",
  "FormatInfo",
  formats,
);

interface TableFunctionRow {
  name: string;
  description: string;
}

const tableFunctions = rows<TableFunctionRow>("SELECT name, description FROM system.table_functions ORDER BY name").map((r) => ({
  name: r.name,
  description: summary(r.description, 300),
}));

write(
  "table-functions.ts",
  "system.table_functions",
  ["export interface TableFunctionInfo {", "  name: string;", "  description?: string;", "}"],
  "TABLE_FUNCTIONS",
  "TableFunctionInfo",
  tableFunctions,
);

interface CombinatorRow {
  name: string;
  syntax: string;
  description: string;
}

const combinators = rows<CombinatorRow>(
  "SELECT name, syntax, description FROM system.aggregate_function_combinators WHERE NOT is_internal ORDER BY name",
).map((r) => ({ name: r.name, syntax: r.syntax.trim(), description: summary(r.description, 300) }));

write(
  "combinators.ts",
  "system.aggregate_function_combinators (internal ones left out)",
  [
    "export interface CombinatorInfo {",
    "  /** The suffix added to an aggregate function name, such as If in sumIf. */",
    "  name: string;",
    "  syntax?: string;",
    "  description?: string;",
    "}",
  ],
  "COMBINATORS",
  "CombinatorInfo",
  combinators,
);

const timeZones = rows<{ time_zone: string }>("SELECT time_zone FROM system.time_zones ORDER BY time_zone").map((r) => ({ name: r.time_zone }));

write("time-zones.ts", "system.time_zones", ["export interface TimeZoneInfo {", "  name: string;", "}"], "TIME_ZONES", "TimeZoneInfo", timeZones);

console.log(
  `Wrote ${functions.length} functions, ${settings.length} settings, ${engines.length} table engines, ` +
    `${formats.length} formats, ${tableFunctions.length} table functions, ${combinators.length} combinators ` +
    `and ${timeZones.length} time zones from ClickHouse ${version}.`,
);
