// Regenerates packages/core/src/generated/ from a ClickHouse source tree and binary.
// Usage: npm run generate -- --src <ClickHouse checkout> --clickhouse <clickhouse binary>

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

const { values: args } = parseArgs({
  options: {
    src: { type: "string" },
    clickhouse: { type: "string" },
  },
});

if (!args.src || !args.clickhouse) {
  console.error("Usage: npm run generate -- --src <ClickHouse checkout> --clickhouse <clickhouse binary>");
  process.exit(2);
}

const outDir = join(import.meta.dirname, "..", "packages", "core", "src", "generated");

function runQuery(query: string): string {
  return execFileSync(args.clickhouse!, ["local", "--query", query], { encoding: "utf8" });
}

const version = runQuery("SELECT version()").trim();

const header = readFileSync(join(args.src, "src", "Parsers", "CommonParsers.h"), "utf8");
const keywords = [...new Set([...header.matchAll(/MR_MACROS\(\w+, "([^"]+)"\)/g)].map((m) => m[1]))].sort();

writeFileSync(
  join(outDir, "keywords.ts"),
  [
    "// Generated by scripts/generate-names.ts from src/Parsers/CommonParsers.h; do not edit.",
    `// ClickHouse ${version}. Multi-word keywords are kept as one phrase, as the parser matches them.`,
    "export const KEYWORDS: readonly string[] = [",
    ...keywords.map((k) => `  ${JSON.stringify(k)},`),
    "];",
    "",
  ].join("\n"),
);

interface Row {
  name: string;
  case_insensitive: number;
  alias_to: string;
}

const rows: Row[] = runQuery(
  "SELECT name, case_insensitive, alias_to FROM system.data_type_families ORDER BY name FORMAT JSONEachRow",
)
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line) as Row);

writeFileSync(
  join(outDir, "data-types.ts"),
  [
    "// Generated by scripts/generate-names.ts from system.data_type_families; do not edit.",
    `// ClickHouse ${version}.`,
    "export interface DataTypeName {",
    "  name: string;",
    "  /** Whether the name may be written in any letter case, like `date` for `Date`. */",
    "  caseInsensitive: boolean;",
    "  /** The type this name is an alias of, or an empty string. */",
    "  aliasTo: string;",
    "}",
    "",
    "export const DATA_TYPES: readonly DataTypeName[] = [",
    ...rows.map(
      (r) =>
        `  { name: ${JSON.stringify(r.name)}, caseInsensitive: ${r.case_insensitive === 1}, aliasTo: ${JSON.stringify(r.alias_to)} },`,
    ),
    "];",
    "",
  ].join("\n"),
);

interface PrivilegeRow {
  privilege: string;
  aliases: string[];
  level: string | null;
}

const privileges: PrivilegeRow[] = runQuery(
  "SELECT privilege, aliases, level FROM system.privileges ORDER BY toString(privilege) FORMAT JSONEachRow",
)
  .trim()
  .split("\n")
  .map((line) => JSON.parse(line) as PrivilegeRow);

// The sources of READ and WRITE: APPLY_FOR_SOURCE(M) lists M(NAME, "aliases"), which go into a std::map.
const accessType = readFileSync(join(args.src, "src", "Access", "Common", "AccessType.h"), "utf8");
const sourceMacro = /#define APPLY_FOR_SOURCE\(M\)([\s\S]*?)\n\n/.exec(accessType)![1]!;
const sources = [...sourceMacro.matchAll(/M\((\w+), "([^"]*)"\)/g)].flatMap((m) => [
  m[1]!,
  ...m[2]!.split(",").map((alias) => alias.trim()),
]);
const sourceNames = [...new Set(sources)].sort();

writeFileSync(
  join(outDir, "privileges.ts"),
  [
    "// Generated by scripts/generate-names.ts from system.privileges and src/Access/Common/AccessType.h; do not edit.",
    `// ClickHouse ${version}.`,
    "export interface Privilege {",
    "  name: string;",
    "  /** Other names GRANT accepts for it. */",
    "  aliases: readonly string[];",
    "  /** What it is granted on, such as GLOBAL, TABLE or SOURCE; null for a group like ALL. */",
    "  level: string | null;",
    "}",
    "",
    "export const PRIVILEGES: readonly Privilege[] = [",
    ...privileges.map(
      (r) =>
        `  { name: ${JSON.stringify(r.privilege)}, aliases: [${r.aliases.map((a) => JSON.stringify(a)).join(", ")}], ` +
        `level: ${JSON.stringify(r.level)} },`,
    ),
    "];",
    "",
    "/** The sources READ and WRITE are granted on, with their aliases, in the order ClickHouse lists them. */",
    "export const SOURCE_NAMES: readonly string[] = [",
    ...sourceNames.map((name) => `  ${JSON.stringify(name)},`),
    "];",
    "",
  ].join("\n"),
);

console.log(
  `Wrote ${keywords.length} keywords, ${rows.length} data types, ${privileges.length} privileges and ` +
    `${sourceNames.length} source names from ClickHouse ${version}.`,
);
