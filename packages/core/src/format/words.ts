/** Every word that is a keyword or part of one. */
export const KEYWORD_WORDS = new Set(KEYWORDS.flatMap((k) => k.toUpperCase().split(" ")));

/** Keyword phrases indexed by their first word, longest first. */
const PHRASES = new Map<string, string[][]>();
for (const keyword of KEYWORDS) {
  const words = keyword.toUpperCase().split(" ");
  const list = PHRASES.get(words[0]!) ?? [];
  list.push(words);
  PHRASES.set(words[0]!, list);
}
for (const list of PHRASES.values()) list.sort((a, b) => b.length - a.length);

/** The keyword phrases that start with `first`, longest first. */
export function phrasesOf(first: string): readonly string[][] {
  return PHRASES.get(first) ?? [];
}

