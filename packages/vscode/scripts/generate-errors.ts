// Writes src/generated/errors.ts, the error codes that test hints name, from a ClickHouse binary:
// npx tsx scripts/generate-errors.ts --clickhouse <clickhouse>
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const at = process.argv.indexOf("--clickhouse");
const binary = at > 0 ? process.argv[at + 1] : undefined;
if (!binary) throw new Error("Pass --clickhouse <clickhouse>");
const run = (sql: string) => execFileSync(binary, ["local", "--query", sql], { encoding: "utf8" }).trim();

const version = run("SELECT version()");
const rows = run("SELECT number, errorCodeToName(number) AS name FROM numbers(100000) WHERE name != '' ORDER BY number FORMAT TSV")
  .split("\n")
  .map((line) => line.split("\t"));
const entries = rows.map(([code, name]) => `  ${name}: ${code},`).join("\n");
const path = join(__dirname, "..", "src", "generated", "errors.ts");
writeFileSync(
  path,
  `// Generated by scripts/generate-errors.ts from errorCodeToName(); do not edit.\n// ClickHouse ${version}.\n` +
    `/** The code of each error name of ClickHouse. */\nexport const ERROR_CODES: Readonly<Record<string, number>> = {\n${entries}\n};\n`,
);
console.log(`Wrote ${rows.length} error codes to ${path}`);
