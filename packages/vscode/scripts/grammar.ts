import { type DataTypeName, SYSTEM_COMMANDS } from "clickhouse-sql-syntax";

// ClickHouse words are ASCII letters, digits, "_" and "$".
const WORD_BEFORE = "(?<![A-Za-z0-9_$])";
const WORD_AFTER = "(?![A-Za-z0-9_$])";
const CONSTANTS = ["NULL", "TRUE", "FALSE"];
const NAME = "(?:[A-Za-z0-9_]|\\$(?=[A-Za-z0-9_]))[A-Za-z0-9_$]*";
// As in highlight(): keywords that a "(" often follows without a call, as in IN (1, 2) or GROUPING SETS (...).
const CLAUSE_WORDS = (
  "ALIAS ALL AND APPLY ARGUMENTS AS BETWEEN BY CASE CHECK CODEC COLUMNS CUBE DEFAULT DESCRIBE DISTINCT " +
  "ELSE EPHEMERAL EXCEPT EXPLAIN FILTER FROM HAVING ILIKE IN INTERPOLATE INTERSECT INTERVAL JOIN KEY " +
  "LATERAL LAYOUT LIFETIME LIKE LIMIT MATERIALIZED NOT OFFSET ON OR OVER PARTITION PREWHERE QUALIFY " +
  "ROLLUP SELECT SETS SETTINGS SOME SOURCE STATISTICS THEN TOP TTL UNION USING VALUES WHEN WHERE WITH"
).split(" ");
// As in highlight(): short interval units, keywords only after a number or a string, as in INTERVAL 1 D.
const UNIT_ABBREVIATIONS = "D DD H HH M MCS MI MM MS N NS Q QQ S SS WK WW YY YYYY".split(" ");
// Words that start a line before a column, as in WHERE date = today(), or before a type, as in FORMAT JSON.
const NOT_COLUMNS = [...CLAUSE_WORDS.filter((word) => word !== "KEY"), "FORMAT", "SET", "WHERE"];
const QUOTED_NAME = '`(?:[^`\\\\]|\\\\.|``)*`|"(?:[^"\\\\]|\\\\.|"")*"';
const STRING_ON_ONE_LINE = "'(?:[^'\\\\]|\\\\.|'')*'";
// Keywords that may follow AS, as in CREATE VIEW v AS SELECT.
const KEYWORDS_AFTER_AS = [
  ...CONSTANTS,
  ...["SELECT", "WITH", "FROM", "MATERIALIZED", "PERMISSIVE", "RESTRICTIVE", "REPLICATED", "NOT"],
];
// As in highlight(): words after which a name is an object, not a function, as in CREATE TABLE t (...).
const OBJECT_WORDS = ["TABLE", "VIEW", "DICTIONARY", "EXISTS", "TO", "INTO", "CLUSTER", "INDEX", "PROJECTION"];
// Characters ClickHouse skips as whitespace or uses in tokens; any other non-ASCII one is an error.
const UNICODE_ALLOWED =
  "\\x{0085}\\x{00A0}\\x{180E}\\x{2000}-\\x{200D}\\x{2028}\\x{2029}\\x{202F}\\x{205F}\\x{2060}" +
  "\\x{3000}\\x{FEFF}\\x{2018}\\x{201C}\\x{2212}";

/**
 * Builds the TextMate grammar from the keyword and data type lists of clickhouse-sql-syntax.
 * It uses the same scope names as highlight() of the library.
 */
export function buildGrammar(keywords: readonly string[], dataTypes: readonly DataTypeName[]): object {
  const keywordWords = new Set(keywords.flatMap(words).map((word) => word.toUpperCase()));
  for (const constant of CONSTANTS) keywordWords.delete(constant);
  for (const unit of UNIT_ABBREVIATIONS) keywordWords.delete(unit);
  const unit = `(?i:${alternation(UNIT_ABBREVIATIONS)})${WORD_AFTER}`;

  // Any spelling the type allows, used where a type must follow (after "::").
  const exactTypes = new Set<string>();
  const anyCaseTypes = new Set<string>();
  // Spellings coloured as types everywhere: as listed, and not an upper-case keyword like SET.
  const bareTypes = new Set<string>();
  for (const type of dataTypes) {
    for (const word of words(type.name)) {
      (type.caseInsensitive ? anyCaseTypes : exactTypes).add(word);
      if (word !== word.toUpperCase() || !keywordWords.has(word)) bareTypes.add(word);
    }
  }

  const anyType = `(?:${alternation(exactTypes)}|(?i:${alternation(anyCaseTypes)}))`;
  const number = "[0-9](?:_?[0-9])*";
  const exponent = `(?:[eE][+-]?${number})?`;
  const hexNumber = "[0-9A-Fa-f](?:_?[0-9A-Fa-f])*";
  // A number and the interval unit after it: INTERVAL 1 D.
  const numberWithUnit = (match: string): object => ({
    match: `(${match})(?:([ \\t]+)(${unit}))?`,
    captures: {
      1: { name: "constant.numeric.sql" },
      3: { name: "keyword.other.sql" },
    },
  });

  return {
    $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
    name: "ClickHouse SQL",
    scopeName: "source.clickhouse-sql",
    comment: "Generated by scripts/generate-grammar.ts from clickhouse-sql-syntax. Do not edit.",
    patterns: [
      { include: "#comments" },
      { include: "#heredoc" },
      { include: "#strings" },
      { include: "#column-definition" },
      { include: "#quoted-identifiers" },
      { include: "#query-parameter" },
      { include: "#numbers" },
      { include: "#cast-type" },
      { include: "#operators" },
      { include: "#punctuation" },
      { include: "#words" },
      { include: "#illegal" },
    ],
    repository: {
      comments: {
        patterns: [
          { include: "#block-comment" },
          { name: "comment.line.sql", match: "(?:--|//|#[ !]).*" },
        ],
      },
      "block-comment": {
        name: "comment.block.sql",
        begin: "/\\*",
        end: "\\*/",
        patterns: [{ include: "#block-comment" }],
      },
      heredoc: {
        name: "string.unquoted.heredoc.sql",
        begin: `${WORD_BEFORE}\\$([A-Za-z0-9_]*)\\$`,
        end: "\\$\\1\\$",
      },
      strings: {
        patterns: [
          { name: "string.quoted.single.sql", match: `${WORD_BEFORE}(?:[xX]'[0-9A-Fa-f]*'|[bB]'[01]*')` },
          // The interval unit after a string: INTERVAL '1' D, and the second one in INTERVAL '1 2' DAY TO H.
          {
            match: `(${STRING_ON_ONE_LINE})([ \\t]+)(${NAME})([ \\t]+)((?i:TO))([ \\t]+)(${unit})`,
            captures: {
              1: { name: "string.quoted.single.sql" },
              3: { name: "keyword.other.sql" },
              5: { name: "keyword.other.sql" },
              7: { name: "keyword.other.sql" },
            },
          },
          {
            match: `(${STRING_ON_ONE_LINE})([ \\t]+)(${unit})`,
            captures: {
              1: { name: "string.quoted.single.sql" },
              3: { name: "keyword.other.sql" },
            },
          },
          quoted("string.quoted.single.sql", "'"),
          { name: "string.quoted.single.sql", begin: "\u2018", end: "\u2019" },
        ],
      },
      "quoted-identifiers": {
        patterns: [
          quoted("variable.other.sql", '"'),
          quoted("variable.other.sql", "`"),
          { name: "variable.other.sql", begin: "\u201C", end: "\u201D" },
        ],
      },
      // A name and its data type at the start of a line or after "(" or ",": (d Date, s String).
      "column-definition": {
        match:
          `(?:^|(?<=[(,]))[ \\t]*(?!(?i:${alternation(NOT_COLUMNS)})${WORD_AFTER})((?![0-9])${NAME}|${QUOTED_NAME})` +
          `([ \\t]+)(${anyType})${WORD_AFTER}`,
        captures: {
          1: { name: "variable.other.sql" },
          3: { name: "storage.type.sql" },
        },
      },
      "query-parameter": {
        name: "variable.parameter.sql",
        match: "\\{\\s*(?![0-9])[A-Za-z0-9_$]+\\s*:\\s*[A-Za-z_$][^{};]*\\}",
      },
      numbers: {
        patterns: [
          // After a dot only a plain integer, so that x.1.2 is x . 1 . 2 as in ClickHouse.
          numberWithUnit(`(?<=\\.)(?>${number})(?![A-Za-z0-9_])`),
          numberWithUnit(
            `${WORD_BEFORE}(?>0[xX]${hexNumber}(?:\\.(?:${hexNumber})?)?(?:[pP][+-]?${number})?` +
              `|0[bB][01](?:_?[0-9])*(?:\\.(?:${number})?)?${exponent}` +
              `|${number}(?:\\.(?:${number})?)?${exponent})(?![A-Za-z0-9_])`,
          ),
          numberWithUnit(`(?<![A-Za-z0-9_$)\\]"\`])(?>\\.${number}${exponent})(?![A-Za-z0-9_])`),
        ],
      },
      "cast-type": {
        patterns: [
          {
            match: `(::)\\s*(${anyType})${WORD_AFTER}`,
            captures: {
              1: { name: "keyword.operator.sql" },
              2: { name: "storage.type.sql" },
            },
          },
          // CAST(x AS Type) and CAST(x AS Type(...)).
          {
            match: `${WORD_BEFORE}((?i:AS))([ \\t]+)(${anyType})${WORD_AFTER}(?=[ \\t]*[()])`,
            captures: {
              1: { name: "keyword.other.sql" },
              3: { name: "storage.type.sql" },
            },
          },
        ],
      },
      operators: {
        name: "keyword.operator.sql",
        match: "<=>|!~\\*|::|->|<=|>=|<>|!=|==|\\|\\||\\|>|~\\*|!~|@@|[-+*/%=<>?:^~|@\\x{2212}]|\\$(?![A-Za-z0-9_])",
      },
      punctuation: {
        name: "punctuation.sql",
        match: "[()\\[\\]{},.;]|\\\\G",
      },
      words: {
        patterns: [
          // Next to a "." a word is a name: db.table, t.column.
          { name: "variable.other.sql", match: `(?<=\\.)${NAME}|${WORD_BEFORE}${NAME}(?=\\s*\\.(?![0-9]))` },
          // The name after FORMAT is an output format, as in FORMAT JSON.
          {
            match: `${WORD_BEFORE}((?i:FORMAT))([ \\t]+)(${NAME})`,
            captures: {
              1: { name: "keyword.other.sql" },
              3: { name: "variable.other.sql" },
            },
          },
          { name: "constant.language.sql", match: `${WORD_BEFORE}(?i:${alternation(CONSTANTS)})${WORD_AFTER}` },
          // An alias after AS, and an engine name after ENGINE =, are names even when they are keywords.
          {
            match:
              `${WORD_BEFORE}((?i:AS))([ \\t]+)(?!(?i:${alternation(KEYWORDS_AFTER_AS)})${WORD_AFTER})` +
              `(${NAME})${WORD_AFTER}(?![ \\t]*[(.])`,
            captures: {
              1: { name: "keyword.other.sql" },
              3: { name: "variable.other.sql" },
            },
          },
          engine("entity.name.function.sql", "(?=[ \\t]*\\()"),
          engine("variable.other.sql", WORD_AFTER),
          { name: "storage.type.sql", match: `${WORD_BEFORE}(?:${alternation(bareTypes)})${WORD_AFTER}` },
          // ALTER TABLE t ADD COLUMN name Type
          {
            match: `${WORD_BEFORE}((?i:COLUMN))([ \\t]+)(${NAME})([ \\t]+)(${anyType})${WORD_AFTER}`,
            captures: {
              1: { name: "keyword.other.sql" },
              3: { name: "variable.other.sql" },
              5: { name: "storage.type.sql" },
            },
          },
          // CREATE TABLE t (...) and INSERT INTO t (...) name a table, not a function; IN (...) stays a keyword.
          {
            match:
              `${WORD_BEFORE}((?i:${alternation(OBJECT_WORDS)}))(\\s+)` +
              `(?!(?i:${alternation(CLAUSE_WORDS)})${WORD_AFTER})(${NAME})(?=[ \\t]*\\()`,
            captures: {
              1: { name: "keyword.other.sql" },
              3: { name: "variable.other.sql" },
            },
          },
          {
            name: "entity.name.function.sql",
            match: `${WORD_BEFORE}(?!(?i:${alternation(CLAUSE_WORDS)})${WORD_AFTER})${NAME}(?=[ \\t]*\\()`,
          },
          // SYSTEM FLUSH LOGS: the words of a SYSTEM command are keywords, as in highlight().
          {
            match: `${WORD_BEFORE}((?i:SYSTEM))([ \\t]+)((?i:${phrases(SYSTEM_COMMANDS)}))${WORD_AFTER}(?![ \\t]*\\.)`,
            captures: {
              1: { name: "keyword.other.sql" },
              3: { patterns: [{ name: "keyword.other.sql", match: NAME }] },
            },
          },
          { name: "keyword.other.sql", match: `${WORD_BEFORE}(?i:${alternation(keywordWords)})${WORD_AFTER}` },
          { name: "variable.other.sql", match: NAME },
        ],
      },
      illegal: {
        name: "invalid.illegal.sql",
        match: `!|\\\\|#|&|[\\x00-\\x08\\x0E-\\x1F\\x7F]|[^\\x00-\\x7F${UNICODE_ALLOWED}]`,
      },
    },
  };
}

// ENGINE = Memory names an engine, and ENGINE = MergeTree() calls one.
function engine(scope: string, after: string): object {
  return {
    match: `${WORD_BEFORE}((?i:ENGINE))([ \\t]*)(=)([ \\t]*)(${NAME})${after}`,
    captures: {
      1: { name: "keyword.other.sql" },
      3: { name: "keyword.operator.sql" },
      5: { name: scope },
    },
  };
}

function words(phrase: string): string[] {
  return phrase.split(" ").filter((word) => word !== "");
}

// Longest first, so that a word is never cut short by one of its prefixes.
function alternation(items: Iterable<string>): string {
  const sorted = [...items].sort((a, b) => b.length - a.length || (a < b ? -1 : a > b ? 1 : 0));
  for (const item of sorted) {
    if (!/^[A-Za-z0-9_$]+$/.test(item)) throw new Error(`Unexpected character in name: ${item}`);
  }
  return sorted.map((item) => item.replaceAll("$", "\\$")).join("|");
}

// Multi-word phrases such as FLUSH LOGS, longest first, with any spaces or tabs between the words.
function phrases(items: Iterable<string>): string {
  const sorted = [...items].sort((a, b) => b.length - a.length || (a < b ? -1 : a > b ? 1 : 0));
  return sorted.map((phrase) => words(phrase).map((word) => alternation([word])).join("[ \\t]+")).join("|");
}

// A quoted token that may span lines, with backslash escapes and a doubled quote inside.
function quoted(name: string, quote: string): object {
  return {
    name,
    begin: quote,
    end: quote,
    applyEndPatternLast: 1,
    patterns: [{ match: `\\\\.|${quote}${quote}` }],
  };
}
